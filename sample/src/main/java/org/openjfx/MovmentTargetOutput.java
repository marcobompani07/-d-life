package org.openjfx;

public class MovmentTargetOutput {
    private double x;
    private double y;

    public MovmentTargetOutput(double x, double y) {
        this.x = x;
        this.y = y;
    }

    public double getX() {
        return this.x;
    }

    public void setX(double x) {
        this.x = x;
    }

    public double getY() {
        return this.y;
    }

    public void setY(double y) {
        this.y = y;
    }

}
